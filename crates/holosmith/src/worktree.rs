//! The session worktree: one git worktree and one branch per session, on the host (HS-025).
//!
//! Spec item 1 names five host commands; this module is those five, the naming rule they share, and
//! since HS-026 the read that says a repository must not be mounted at all:
//!
//! ```text
//! git worktree add -b agent/<id> <projects>/.worktrees/<id> HEAD
//! git rev-list --count <base_commit>..agent/<id>
//! git worktree remove --force <projects>/.worktrees/<id>
//! git branch -D agent/<id>
//! git worktree prune
//! ```
//!
//! **No fetch, anywhere.** The session branch is created from a commit the project repository already
//! has, so there is nothing to bring in from a remote and nothing here names one.
//!
//! Since HS-026 the module also holds the readings that say a repository must not be mounted at all
//! ([`refuse`]): they are the same kind of question — what does this repository say about itself — and
//! they run before the first `worktree add`, so a refused create leaves nothing behind. They are not
//! one of the five commands, and they write nothing.
//!
//! Since HS-043 the module also holds the rule that says what a **teardown** leaves in the repository
//! ([`Retained`], [`Worktree::retained`]): branch `agent/<id>` when it has commits beyond its base and
//! is not merged into a target branch, and `refs/holosmith/wip/<id>` when its tree differs from the
//! branch's. It is here rather than in the delete flow for the reason ADR-0029 gives: `remove` is the
//! function that deletes the branch, so the rule that says "not this one" has to be answered beside it —
//! and then a real repository in a `TempDir` can prove it with no daemon, no backend and no request.
//!
//! Three things this module measured, and each of them is a bug if it is forgotten:
//!
//! - **Every path is absolute.** `git worktree add` resolves a relative `<path>` against the
//!   *repository*, not against the caller's working directory (git 2.43: `git -C repo worktree add
//!   ../x` lands inside the repository). `<projects_root>` is validated as an absolute path, so the
//!   path built here is absolute too.
//! - **`git worktree list --porcelain` prints the resolved path**, so a projects root reached through a
//!   symlink does not compare equal to the path this module built. The registration check canonicalises
//!   both sides for that reason.
//! - **The "already gone" answers are exits, not exceptions**: removing a worktree that is not
//!   registered exits 128 and deleting a branch that does not exist exits 1. Both mean teardown has
//!   nothing left to do, and `remove` asks the question *before* running either command rather than
//!   reading git's English.
//!
//! The module is synchronous and `std`-only: it runs one program and reads one answer. The Docker
//! backend calls it from a blocking task, because the provisioner is a `tokio` task and a subprocess in
//! one blocks a worker for as long as git takes.
//!
//! Nothing here logs. A failure answers a [`GitError`], whose sentence is what the row's
//! `status_reason` and the transcript show the operator.

use std::fmt;
use std::path::{Path, PathBuf};
use std::process::Command;

/// The directory under the projects root that holds every session's worktree: `<projects>/.worktrees/<id>`.
pub const WORKTREES: &str = ".worktrees";

/// The prefix of every session branch: `agent/<id>` (the glossary's **Session branch**).
pub const BRANCH_PREFIX: &str = "agent/";

/// One session's worktree, named but not necessarily made: the repository its branch lives in, the
/// directory the agent edits, and the branch the commit goes to.
///
/// A value rather than four arguments, because every operation the module offers is a question about
/// the same three paths, and because the branch name and the directory are derived from the session id
/// in exactly one place (`Session`'s own doc spells the same rule).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Worktree {
    /// 16 lowercase hex characters: what the branch, the directory and the snapshot ref are named for.
    ///
    /// Kept as a field since HS-043 as well as the branch, because the snapshot ref
    /// (`refs/holosmith/wip/<id>`) is the one name this struct does not carry in `branch` or `path`.
    pub id: String,
    /// `<projects_root>/<project>`: the repository the branch lives in, and where git runs.
    ///
    /// `project` is one path segment — the create validates it with `validate_project` before a row
    /// exists, so this path cannot leave the projects root.
    pub repository: PathBuf,
    /// `<projects_root>/.worktrees/<id>`: the session's files, and the container's `/work` (HS-027).
    pub path: PathBuf,
    /// `agent/<id>`.
    pub branch: String,
}

impl Worktree {
    /// The worktree of session `id` in `project`, from the machine's projects root.
    ///
    /// `id` is 16 lowercase hex characters generated by the database (ADR-0011), so it is safe in a
    /// branch name and in a path; `project` is validated by the create. This function therefore does no
    /// validation of its own — it is the naming rule, not the guard.
    /// The rule itself is stated three times and only as text: this function, [`crate::backend::Step`]'s
    /// `Worktree` variant, and `GLOSSARY.md`'s **Worktree** entry.
    pub fn of(projects_root: &Path, project: &str, id: &str) -> Self {
        Self {
            id: id.to_string(),
            repository: repository_of(projects_root, project),
            path: projects_root.join(WORKTREES).join(id),
            branch: format!("{BRANCH_PREFIX}{id}"),
        }
    }

    /// Make the worktree, or adopt the one that is already there, and answer the commit its branch
    /// starts from.
    ///
    /// **Idempotent, because a provision is not a first provision.** The provisioner runs all four steps
    /// on every provision, and `POST /resume` re-provisions a session that was only stopped: its
    /// worktree, its branch and every commit on it are still there, and a step that could only ever run
    /// once would be a session that cannot be resumed (ADR-0022).
    ///
    /// `base` is the row's `base_commit` when it has one. It has to win over the branch's current head:
    /// a session that has committed three times must keep pointing `ahead` at where it *started*. Three
    /// states, and each one has its own command:
    ///
    /// 1. registered and branch present — nothing to do, and the answer says the worktree was
    ///    **adopted** rather than made: see [`Ensured::created`];
    /// 2. branch present, nothing registered (a teardown interrupted between its two commands) — attach
    ///    the existing branch, which keeps its commits, and that is an adoption too;
    /// 3. no branch — create it with `-b`, from `base` or (first provision) from `HEAD`.
    pub fn ensure(&self, base: Option<&str>) -> Result<Ensured, GitError> {
        let branch_exists = self.branch_exists()?;
        if self.registered()? {
            if branch_exists {
                return Ok(Ensured {
                    base_commit: match base {
                        Some(base) => base.to_string(),
                        None => self.run(&["rev-parse", &self.branch])?,
                    },
                    created: false,
                });
            }
            // A registration whose branch is gone is not a state this code makes; it is a repository
            // somebody edited. Recreating the worktree is what the operator asked for, and it is safe:
            // without the branch, the directory's files are the only copy of anything in it.
            self.run(&["worktree", "remove", "--force", &self.path_arg()])?;
        }
        let created = if branch_exists {
            self.run(&["worktree", "add", &self.path_arg(), &self.branch])?;
            false
        } else {
            self.run(&[
                "worktree",
                "add",
                "-b",
                &self.branch,
                &self.path_arg(),
                base.unwrap_or("HEAD"),
            ])?;
            true
        };
        Ok(Ensured {
            base_commit: match base {
                Some(base) => base.to_string(),
                None => self.run(&["rev-parse", &self.branch])?,
            },
            created,
        })
    }

    /// How many commits the branch has that `base_commit` does not: the story's second command.
    ///
    /// The story's own demonstration — "commit in it, see `ahead` increment" — is this number, and the
    /// surface that publishes it is `GET /api/sessions/:id/changes` (spec item 12, HS-061), which is why
    /// the number is neither a column nor an endpoint here: a list endpoint that ran git per row would be
    /// a second data path over the same repository.
    pub fn ahead(&self, base_commit: &str) -> Result<u64, GitError> {
        let range = format!("{base_commit}..{}", self.branch);
        let text = self.run(&["rev-list", "--count", &range])?;
        text.parse().map_err(|_| GitError {
            command: self.command(&["rev-list", "--count", &range]),
            detail: format!("git printed {text:?}, which is not a count"),
        })
    }

    /// What a teardown of this session must leave in the repository (HS-043, spec item 9).
    ///
    /// Two questions, each answered by the repository itself:
    ///
    /// - **the branch**, kept when it has commits beyond `base` and the merge question did not answer
    ///   *yes* for a target. `base` is the row's `base_commit`; a row without one never finished its
    ///   worktree step, so the question is unanswerable and the answer is [`Retained::Unknown`] — which
    ///   keeps.
    /// - **the snapshot ref**, kept when it exists and its tree differs from the branch's. Nothing here
    ///   deletes that ref; the answer decides whether the operator is *told* about it (and given the
    ///   recovery command), which is why a session that settled with nothing uncommitted names nothing
    ///   (ADR-0049 removes the ref in exactly that case).
    ///
    /// A repository that is not there has none of this session's names in it, and that is not an error:
    /// teardown's job is to leave nothing behind, and [`Retained::nothing`] is the answer (ADR-0023).
    pub fn retained(&self, base: Option<&str>, targets: &[String]) -> Result<Retained, GitError> {
        if !self.repository.is_dir() {
            return Ok(Retained::nothing());
        }
        let Some(base) = base else {
            return Ok(Retained::Unknown);
        };
        let head = self.branch_head()?;
        let branch = match head.as_deref() {
            // A branch that is not there is nothing to keep, and there is no merge to ask about.
            None => None,
            Some(_) if self.ahead(base)? == 0 => None,
            Some(_) => match self.merged_into(targets)? {
                Merged::Yes => None,
                Merged::No | Merged::Unasked => Some(self.branch.clone()),
            },
        };
        Ok(Retained::Known {
            branch,
            wip: self.differing_ref(head.as_deref())?,
        })
    }

    /// Remove the worktree, its branch and its registration: the story's teardown.
    ///
    /// `retained` is [`Worktree::retained`]'s answer: the branch it names is **not** deleted, because it
    /// holds work nothing else has (HS-043). The registration and the directory go either way — a branch
    /// is a name in the repository, not a copy of the worktree, and the files the agent left are the
    /// snapshot's subject rather than the branch's.
    ///
    /// **A missing worktree is not an error, and neither is a missing branch or a missing project
    /// repository.** Teardown's job is to leave nothing behind, and a thing that is not there is nothing
    /// behind. This is not politeness: the delete flow keeps the row `deleting` when a backend fails
    /// (ADR-0023), so a teardown that refused over an already-absent directory would leave a session that
    /// can never be removed.
    ///
    /// A *directory* that exists but is not registered as a worktree is left alone: git will not remove
    /// it, and an orphan from a crashed run is HS-044's to prune. Every path this module drives leaves
    /// the registration clean, which is what that story starts from.
    pub fn remove(&self, retained: &Retained) -> Result<(), GitError> {
        if !self.repository.is_dir() {
            return Ok(());
        }
        if self.registered()? {
            self.run(&["worktree", "remove", "--force", &self.path_arg()])?;
        }
        if !retained.keeps_branch() && self.branch_exists()? {
            self.run(&["branch", "-D", &self.branch])?;
        }
        // Last, and always: a registration whose directory a crash left behind is what `prune` is for.
        self.run(&["worktree", "prune"])?;
        Ok(())
    }

    /// Whether git has this path registered as a worktree of the repository.
    ///
    /// The path is compared after `canonicalize`, because `git worktree list --porcelain` prints the
    /// resolved path and a projects root may be reached through a symlink.
    ///
    /// Public since HS-052, which asks the same question of the same repository from the changes view: a
    /// pruned worktree's directory can still be there, and every read inside it would then fail with "not a
    /// git repository". One question, one function — [`crate::changes`] does not spell it again.
    pub fn registered(&self) -> Result<bool, GitError> {
        let listing = self.run(&["worktree", "list", "--porcelain"])?;
        let ours = std::fs::canonicalize(&self.path).ok();
        for entry in listing
            .lines()
            .filter_map(|line| line.strip_prefix("worktree "))
        {
            let entry = Path::new(entry);
            if entry == self.path {
                return Ok(true);
            }
            if let Some(ours) = &ours
                && std::fs::canonicalize(entry).is_ok_and(|theirs| &theirs == ours)
            {
                return Ok(true);
            }
        }
        Ok(false)
    }

    /// Whether the branch exists in the repository.
    fn branch_exists(&self) -> Result<bool, GitError> {
        Ok(self.branch_head()?.is_some())
    }

    /// The commit `agent/<id>` points at, or `None` when there is no such branch.
    ///
    /// `rev-parse --verify --quiet` answers 1 for "no such ref" and prints nothing; any other failure is
    /// a real one and is reported, because a repository that cannot be read is not a missing branch.
    ///
    /// Public since HS-052: the changes view's `head` is this commit, not the worktree's checkout, because
    /// `ahead`, `behind` and the file list are all about the branch.
    pub fn branch_head(&self) -> Result<Option<String>, GitError> {
        let args = ["rev-parse", "--verify", "--quiet", &self.branch_ref()];
        let output = self.output(&args)?;
        match output.status.code() {
            Some(0) => Ok(Some(
                String::from_utf8_lossy(&output.stdout).trim().to_string(),
            )),
            Some(1) => Ok(None),
            _ => Err(self.error(&args, &output)),
        }
    }

    /// Whether `agent/<id>` is already merged into one of the configured targets (HS-043).
    ///
    /// One `merge-base --is-ancestor` per target, and **only per target this repository has**: the
    /// config's default list names both `main` and `master` because a machine has one of them, so a name
    /// that is not there is not a merge. A repository with none of them cannot answer at all, and an
    /// unanswerable question keeps the branch ([`Merged::Unasked`]).
    fn merged_into(&self, targets: &[String]) -> Result<Merged, GitError> {
        let mut asked = false;
        for target in targets {
            let reference = format!("refs/heads/{target}");
            let exists = ["rev-parse", "--verify", "--quiet", reference.as_str()];
            let output = self.output(&exists)?;
            match output.status.code() {
                Some(0) => {}
                Some(1) => continue,
                _ => return Err(self.error(&exists, &output)),
            }
            asked = true;
            let args = ["merge-base", "--is-ancestor", &self.branch, &reference];
            let output = self.output(&args)?;
            match output.status.code() {
                Some(0) => return Ok(Merged::Yes),
                Some(1) => {}
                _ => return Err(self.error(&args, &output)),
            }
        }
        Ok(if asked { Merged::No } else { Merged::Unasked })
    }

    /// `refs/holosmith/wip/<id>` when it exists and holds work the branch does not (HS-043).
    ///
    /// `git diff --quiet <ref> <branch>` is the whole question, and git spells it as one: exit 0 means the
    /// two revisions have the same tree, exit 1 means they differ. With no branch there is nothing to be
    /// equal to, so the ref is a difference. Nothing deletes the ref either way — this decides only
    /// whether the operator is told about it.
    fn differing_ref(&self, branch_head: Option<&str>) -> Result<Option<String>, GitError> {
        let reference = crate::snapshot::reference(&self.id);
        let verify = ["rev-parse", "--verify", "--quiet", reference.as_str()];
        let output = self.output(&verify)?;
        match output.status.code() {
            Some(0) => {}
            Some(1) => return Ok(None),
            _ => return Err(self.error(&verify, &output)),
        }
        let Some(branch_head) = branch_head else {
            return Ok(Some(reference));
        };
        let args = ["diff", "--quiet", reference.as_str(), branch_head];
        let output = self.output(&args)?;
        match output.status.code() {
            Some(0) => Ok(None),
            Some(1) => Ok(Some(reference)),
            _ => Err(self.error(&args, &output)),
        }
    }

    /// `refs/heads/agent/<id>`, the fully qualified name `rev-parse --verify` needs so that a branch name
    /// and a tag of the same name cannot be confused for one another.
    fn branch_ref(&self) -> String {
        format!("refs/heads/{}", self.branch)
    }

    /// The worktree's path as the argument git is given: absolute, as built by [`Self::of`].
    fn path_arg(&self) -> String {
        self.path.to_string_lossy().into_owned()
    }

    /// Run one git command in the repository and answer its trimmed stdout; a non-zero exit is a failure.
    fn run(&self, args: &[&str]) -> Result<String, GitError> {
        git_run(&self.repository, args)
    }

    /// Spawn git in the repository. Only an inability to start it is checked here; the exit status is the
    /// caller's question, because "no such branch" is an answer and not a failure.
    fn output(&self, args: &[&str]) -> Result<std::process::Output, GitError> {
        git_output(&self.repository, args)
    }

    /// What git said about `args`, as the operator reads it: the command, then git's own last words.
    fn error(&self, args: &[&str], output: &std::process::Output) -> GitError {
        git_error(&self.repository, args, output)
    }

    /// The command as an operator would type it, for a failure's sentence.
    fn command(&self, args: &[&str]) -> String {
        git_command(&self.repository, args)
    }
}
/// What a teardown leaves in the repository, and — when it can say — what is there (HS-043).
///
/// Two answers, because the rule and the report are the same decision:
///
/// - [`Retained::Known`] is the repository's answer. Either name may be `None`, and `None` for both is the
///   ordinary case — a session that committed nothing worth keeping.
/// - [`Retained::Unknown`] is "this question has no answer here": a repository git cannot read, or a row
///   with no `base_commit` to measure ahead from. **It keeps the branch**, because "cannot tell" must never
///   mean "delete", and the delete's answer claims nothing rather than claiming something it does not know.
///
/// The names are spelled fully (`agent/<id>`, `refs/holosmith/wip/<id>`) because they are what the
/// operator is told and what the recovery command runs against; a short name would be a second spelling.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Retained {
    /// The repository answered: these names survive.
    Known {
        /// `agent/<id>` when it holds work nothing else has.
        branch: Option<String>,
        /// `refs/holosmith/wip/<id>` when it holds work the branch does not.
        wip: Option<String>,
    },
    /// The question has no answer: the repository could not be read, or the row has no base commit.
    ///
    /// Both keep the branch and make the delete's answer `kept: null`, because neither is evidence that there
    /// is nothing to keep.
    Unknown,
}

impl Retained {
    /// Nothing survives: a repository that is not there, a session that never had a worktree, and a
    /// backend that keeps no repository at all (the stub, ADR-0015).
    pub fn nothing() -> Self {
        Self::Known {
            branch: None,
            wip: None,
        }
    }

    /// Whether [`Worktree::remove`] must leave `agent/<id>` alone.
    ///
    /// [`Retained::Unknown`] answers `true`: a branch deleted because a repository could not be read is
    /// work lost to a filesystem problem, which is the one thing a delete must not do.
    pub fn keeps_branch(&self) -> bool {
        match self {
            Self::Known { branch, .. } => branch.is_some(),
            Self::Unknown => true,
        }
    }

    /// The spec's recovery command, when a snapshot ref survives the teardown.
    ///
    /// One spelling, here, because two — the answer's and the page's — is how a command an operator copies
    /// stops being the command that works. `?force=true` does not change it.
    pub fn recovery(&self) -> Option<String> {
        match self {
            Self::Known {
                wip: Some(reference),
                ..
            } => Some(format!("git branch rescue {reference}")),
            _ => None,
        }
    }
}

/// The answer to "is this branch already in a target?" (HS-043), with the third answer the two booleans
/// cannot carry.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Merged {
    /// It is an ancestor of a target this repository has: the work is already where it belongs.
    Yes,
    /// It is not an ancestor of any target, and at least one was asked.
    No,
    /// The repository has none of the configured targets, so nothing answered — and an unanswerable
    /// question keeps the branch.
    Unasked,
}

/// The project repository `project` lives in, under the machine's projects root: `<projects>/<project>`.
///
/// A function rather than a second `join` at each site, because a create needs the repository *before* a
/// session — and the id [`Worktree::of`] would build a worktree from — exists (HS-026).
///
/// `project` is one path segment: the create's `validate_project` is what keeps it inside the projects
/// root, so this is the naming rule and not the guard.
pub fn repository_of(projects_root: &Path, project: &str) -> PathBuf {
    projects_root.join(project)
}

/// Why a project's repository must not be mounted into a session's container (HS-026, spec item 1).
///
/// Three refusals the spec names, plus the fourth answer that is not a policy: a repository git cannot
/// read has not been checked at all, and saying it may be mounted would be a lie.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Refusal {
    /// `<project>/.git` is not a directory: a linked worktree, a submodule checkout, or no checkout.
    NotADirectory,
    /// The repository has submodules, whose hooks would live under `.git/modules` inside the mount.
    SubmodulesPresent,
    /// `extensions.worktreeConfig` is on, which would let the agent write a per-worktree config.
    WorktreeConfigEnabled,
    /// `git` could not read the repository, so nothing about it can be promised.
    Unreadable(GitError),
}

/// The one `git` reading the refusal rules make: the repository's own answer about
/// `extensions.worktreeConfig`.
///
/// **`--local` is load-bearing.** `git config --get` without a scope reads system, global and local
/// merged, so a `extensions.worktreeConfig = true` in the service user's `~/.gitconfig` would refuse every
/// project on the machine — and `extensions.*` is a repository-format key that git itself honours only from
/// the repository's own config. `--type=bool` so git's spellings (`true`, `yes`, `on`, `1`) all answer one
/// word.
const CONFIG_READ: &[&str] = &[
    "config",
    "--local",
    "--type=bool",
    "--get",
    "extensions.worktreeConfig",
];

/// Whether `repository` may be mounted into a session's container, and why not when it may not
/// (HS-026).
///
/// The checks are spec item 1's, and they run in that order — the cheapest and most fundamental first:
///
/// - **`.git` is a directory.** A `.git` *file* means the checkout is a linked worktree or a submodule,
///   whose repository lives somewhere this mount would not cover.
/// - **No submodules.** `.gitmodules` is the declaration and `.git/modules` is the initialized copy; the
///   spec's hole is the hooks under the latter, and an agent holding `.gitmodules` and a writable
///   `.git/modules` can reach them by initialising a submodule itself. Either one refuses.
/// - **`extensions.worktreeConfig` is off.** With it on, git reads a per-worktree config file that lives
///   in the worktree — the directory the agent owns — so the repository's settings stop being
///   host-only.
///
/// One `git` read, not three: the first two are filesystem facts and the third is `git config`. Everything
/// here is read-only, and this is called **before** the first `worktree add`, so a refused create leaves no
/// row, no directory and no branch behind.
pub fn refuse(repository: &Path) -> Result<(), Refusal> {
    if !repository.join(".git").is_dir() {
        return Err(Refusal::NotADirectory);
    }
    if repository.join(".gitmodules").exists() || repository.join(".git").join("modules").exists() {
        return Err(Refusal::SubmodulesPresent);
    }
    // `--type=bool` so git's own spellings (`true`, `yes`, `on`, `1`) all answer one word. An unset key
    // exits 1 with no output, which is the common case and not a failure; anything else means the
    // repository could not be read.
    let output = git_output(repository, CONFIG_READ).map_err(Refusal::Unreadable)?;
    let value = String::from_utf8_lossy(&output.stdout).trim().to_string();
    match output.status.code() {
        Some(0) if value == "true" => Err(Refusal::WorktreeConfigEnabled),
        Some(0) | Some(1) => Ok(()),
        _ => Err(Refusal::Unreadable(git_error(
            repository,
            CONFIG_READ,
            &output,
        ))),
    }
}

/// Every worktree path `repository` registers, in git's own (resolved) spelling (HS-044).
///
/// The startup reconcile's reader. A directory under `<projects>/.worktrees/` that no row owns is an orphan,
/// and whether a repository registered it decides how it goes: a registered one is taken with
/// `git worktree remove` (which cleans the administrative entry too, and with [`Retained::Unknown`] keeps the
/// branch), an unregistered one is left to the filesystem because nothing registered anything.
///
/// A path is printed raw and unquoted by `--porcelain` (HS-025's measurement), which is why the caller
/// compares canonicalised parents rather than trusting one spelling of the projects root.
///
/// Since HS-054 this is [`checkouts`] with the branches dropped: one parser of one command, because a second
/// one would be a second answer to "what does git's listing say".
pub fn registrations(repository: &Path) -> Result<Vec<PathBuf>, GitError> {
    Ok(checkouts(repository)?
        .into_iter()
        .map(|checkout| checkout.path)
        .collect())
}

/// One checkout git has registered for a repository, and the branch it has checked out (HS-054).
///
/// `branch` is the **short** name (`main`, not `refs/heads/main`), because that is the word the rest of the
/// build uses — the config's `[merge] targets` and the request's `target` — and `None` means the checkout holds
/// a detached HEAD, which is not a branch and therefore cannot be "the target checked out somewhere".
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Checkout {
    /// The path git printed, which `--porcelain` prints resolved and unquoted (HS-025's measurement).
    pub path: PathBuf,
    /// The branch this checkout has checked out, or `None` when its HEAD is detached.
    pub branch: Option<String>,
    /// Whether git calls this registration **prunable**: the directory is gone and `git worktree prune` has not
    /// run yet.
    ///
    /// A field rather than a filter, because the two readers want different things from it: the startup sweep
    /// wants every registration it can compare against the filesystem, and the merge wants only the ones with a
    /// **working tree**. A prunable registration has none, so refusing a merge because the target is "checked
    /// out" there would refuse for a reason that is not true — the merge goes through the ref instead, and
    /// HS-052's landmine is exactly such a registration.
    pub prunable: bool,
}

/// Every checkout `repository` registers, with the branch each one holds (HS-054).
///
/// `git worktree list --porcelain` prints one block per checkout — `worktree <path>`, `HEAD <sha>`, then
/// either `branch refs/heads/<name>` or `detached`, and `prunable <reason>` when the directory is gone —
/// separated by a blank line. The merge needs the *branch*, which [`registrations`] throws away: "is the target
/// checked out anywhere" and, if so, "where" are one question, and the answer decides whether the target is
/// updated in a working tree or through the ref.
///
/// A block carries a branch only when it has one, and `prunable` only when git says so, so the walk keeps the
/// latest `worktree` line and fills the rest of its own block. `locked` and a checkout's own `HEAD` are ignored:
/// neither answers a question this build asks of one.
pub fn checkouts(repository: &Path) -> Result<Vec<Checkout>, GitError> {
    let listing = git_run(repository, &["worktree", "list", "--porcelain"])?;
    Ok(parse_checkouts(&listing))
}

/// The listing's blocks as [`Checkout`]s — split out so the shapes git prints are testable with no repository.
fn parse_checkouts(listing: &str) -> Vec<Checkout> {
    let mut found: Vec<Checkout> = Vec::new();
    for line in listing.lines() {
        if let Some(path) = line.strip_prefix("worktree ") {
            found.push(Checkout {
                path: PathBuf::from(path),
                branch: None,
                prunable: false,
            });
        } else if let Some(reference) = line.strip_prefix("branch ")
            && let Some(checkout) = found.last_mut()
        {
            checkout.branch = reference.strip_prefix("refs/heads/").map(str::to_string);
        } else if line.starts_with("prunable ")
            && let Some(checkout) = found.last_mut()
        {
            checkout.prunable = true;
        }
    }
    found
}

// The four functions below are the crate's one way to spawn git: `Command::new("git")` appears here and
// nowhere else in `src/` (HS-025), which is why HS-052's changes view calls them into this module rather
// than writing a fifth `-C` and a fifth error sentence. They are `pub(crate)` and not `pub` because the
// `GitError` sentence they build is an operator's, not an API's.

/// Run one git command in `repository` and answer its trimmed stdout; a non-zero exit is a failure.
pub(crate) fn git_run(repository: &Path, args: &[&str]) -> Result<String, GitError> {
    let output = git_output(repository, args)?;
    if !output.status.success() {
        return Err(git_error(repository, args, &output));
    }
    Ok(String::from_utf8_lossy(&output.stdout).trim().to_string())
}

/// Spawn git in `repository`. Only an inability to start it is checked here; the exit status is the
/// caller's question, because "no such branch" is an answer and not a failure.
pub(crate) fn git_output(
    repository: &Path,
    args: &[&str],
) -> Result<std::process::Output, GitError> {
    Command::new("git")
        .arg("-C")
        .arg(repository)
        .args(args)
        .output()
        .map_err(|error| GitError {
            command: git_command(repository, args),
            detail: format!("git is not runnable ({error}): install git 2.38 or newer"),
        })
}

/// What git said about `args`, as the operator reads it: the command, then git's own last words.
pub(crate) fn git_error(
    repository: &Path,
    args: &[&str],
    output: &std::process::Output,
) -> GitError {
    git_error_from(git_command(repository, args), &output.stderr, output.status)
}

/// The same sentence for a caller that read git's streams itself instead of collecting an [`Output`].
///
/// `changes::run_patch` is that caller: a patch is bounded rather than buffered, so its stdout is consumed in
/// chunks and stderr on its own thread, and there is no `Output` to hand over. One spelling of "what git said"
/// is what keeps a failure's sentence the same whichever reader reported it.
///
/// [`Output`]: std::process::Output
pub(crate) fn git_error_from(
    command: String,
    stderr: &[u8],
    status: std::process::ExitStatus,
) -> GitError {
    let said = String::from_utf8_lossy(stderr);
    let detail = said.trim();
    GitError {
        command,
        detail: if detail.is_empty() {
            format!("git exited {status} without saying why")
        } else {
            detail.to_string()
        },
    }
}

/// The command as an operator would type it, for a failure's sentence.
pub(crate) fn git_command(repository: &Path, args: &[&str]) -> String {
    format!("git -C {} {}", repository.display(), args.join(" "))
}

/// What one [`Worktree::ensure`] did.
///
/// Two answers, because two readers need different halves: the provisioner wants the base commit (for the
/// row) and whether the worktree is this provision's doing (for the undo, see [`Provisioned`]'s
/// `undoable`), and HS-061's changes sheet wants the base alone.
///
/// [`Provisioned`]: crate::backend::Provisioned
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Ensured {
    /// The commit the branch starts from: the one this provision was told to use, or the one it found.
    pub base_commit: String,
    /// `false` when the worktree — and every commit on it — was the session's before this call. A step
    /// that only adopted has nothing to take back.
    pub created: bool,
}

/// Why a git command did not do what was asked.
///
/// Two parts, because both are the operator's: `command` is what ran (the repository and the arguments,
/// so a session's failure names its own project) and `detail` is git's answer. The sentence reaches the
/// row's `status_reason` and the transcript, so it is written to be read rather than parsed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GitError {
    pub command: String,
    pub detail: String,
}

impl fmt::Display for GitError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}: {}", self.command, self.detail)
    }
}

impl std::error::Error for GitError {}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_worktree_config_read_is_local_and_typed() {
        // Two facts and both are the rule: without `--local` a global `extensions.worktreeConfig` would
        // refuse every project on the machine (and git itself honours the key only from the repository's
        // own config), and without `--type=bool` git's spellings (`on`, `yes`, `1`) would each need an arm.
        // A behavioural test cannot set this process's global git config: `std::env::set_var` is `unsafe`
        // in edition 2024 and this crate denies `unsafe`, so the spelling is what is pinned.
        assert_eq!(
            CONFIG_READ[1], "--local",
            "the read is not the repository's"
        );
        assert_eq!(CONFIG_READ[2], "--type=bool", "the read is not typed");
        assert_eq!(
            CONFIG_READ[CONFIG_READ.len() - 1],
            "extensions.worktreeConfig"
        );
    }

    #[test]
    fn the_three_block_shapes_git_prints_are_read_apart() {
        // One listing, hand-written in the shape git 2.43 prints (measured): the project's checkout on a
        // branch, a session's worktree on another, a detached checkout, and a **prunable** registration — a
        // directory that is gone and has not been pruned. The last is the one that matters to the merge: a
        // `409 target_checked_out` there would refuse for a reason that is not true, so the flag has to survive
        // the parse rather than be assumed absent.
        let listing = "worktree /projects/holosmith\nHEAD 0123456\nbranch refs/heads/main\n\n\
                       worktree /projects/.worktrees/abc\nHEAD 789abcd\nbranch refs/heads/agent/abc\n\n\
                       worktree /projects/elsewhere\nHEAD fedcba9\ndetached\n\n\
                       worktree /projects/gone\nHEAD 1234567\nbranch refs/heads/trunk\nprunable gitdir file \
                       points to non-existent path\n\n";
        let found = parse_checkouts(listing);
        assert_eq!(found.len(), 4, "{found:?}");
        assert_eq!(found[0].path, PathBuf::from("/projects/holosmith"));
        assert_eq!(found[0].branch.as_deref(), Some("main"));
        assert!(!found[0].prunable);
        assert_eq!(found[1].branch.as_deref(), Some("agent/abc"));
        assert_eq!(found[2].branch, None, "a detached checkout has no branch");
        assert!(!found[2].prunable, "the flag leaked from another block");
        assert_eq!(found[3].branch.as_deref(), Some("trunk"));
        assert!(found[3].prunable, "the prunable block lost its flag");
    }
}
