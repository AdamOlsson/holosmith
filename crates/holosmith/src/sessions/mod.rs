//! The `sessions` row: what a session is stored as, and the types the repository stores it with
//! (HS-007).
//!
//! The six statuses live in an enum here rather than in a `CHECK` constraint, so a corrupt row is
//! an error at read time naming the text that was found, and the transition rules arrive without
//! a migration that has to rewrite a constraint (ADR-0011).

pub mod repository;

use std::fmt;
use std::str::FromStr;

/// One of the six session statuses, spelled exactly as the spec spells them (item 8).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Status {
    Starting,
    Idle,
    Running,
    Stopped,
    Error,
    Deleting,
}

impl Status {
    /// Every status, in the spec's order: one list for the state filter, the error message and
    /// the tests.
    pub const ALL: [Status; 6] = [
        Status::Starting,
        Status::Idle,
        Status::Running,
        Status::Stopped,
        Status::Error,
        Status::Deleting,
    ];

    /// The text the `status` column holds.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Starting => "starting",
            Self::Idle => "idle",
            Self::Running => "running",
            Self::Stopped => "stopped",
            Self::Error => "error",
            Self::Deleting => "deleting",
        }
    }
}

impl FromStr for Status {
    type Err = RepoError;

    /// Anything that is not one of the six is refused with the text that was found, so a corrupt
    /// row says which value it holds instead of a bare "invalid status".
    fn from_str(text: &str) -> Result<Self, Self::Err> {
        Self::ALL
            .into_iter()
            .find(|status| status.as_str() == text)
            .ok_or_else(|| RepoError::Status(text.to_string()))
    }
}

impl fmt::Display for Status {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// One `sessions` row. `PartialEq` is what makes "reads back identically" an assertion rather
/// than a field-by-field ceremony.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Session {
    /// 16 lowercase hexadecimal characters, generated by SQLite (ADR-0011).
    pub id: String,
    pub project: String,
    pub model: String,
    pub thinking: String,
    /// `''` until the provisioner runs.
    pub worktree: String,
    /// `None` until a worktree exists.
    pub base_commit: Option<String>,
    pub status: Status,
    pub status_reason: Option<String>,
    /// The idempotency key the create carried; `None` is not a key.
    pub client_key: Option<String>,
    /// The spec's `network INTEGER` column, as the checkbox a client sends.
    pub network: bool,
    pub created_at: i64,
    /// What the cap's LRU eviction orders by (spec item 7, HS-020).
    pub last_active_at: i64,
    /// `Some` exactly while the status is `stopped`: set when it becomes stopped, cleared when
    /// the session resumes (spec item 15).
    pub stopped_at: Option<i64>,
    pub usage_in: u64,
    pub usage_out: u64,
}

/// What a caller supplies to create a session; everything else is the repository's or `now`.
#[derive(Debug, Clone)]
pub struct NewSession {
    pub project: String,
    pub model: String,
    pub thinking: String,
    pub network: bool,
    pub client_key: Option<String>,
    pub base_commit: Option<String>,
}

/// Why a repository call failed.
#[derive(Debug)]
pub enum RepoError {
    /// SQLite refused a statement of the named call, so an operator reading
    /// `create: database is locked` knows which one — the same convention `DbError::Sqlite`
    /// follows by naming the file it is about.
    Sqlite {
        operation: &'static str,
        source: rusqlite::Error,
    },
    /// A row's `status` is not one of the six; it carries the text that was found.
    Status(String),
}

impl RepoError {
    /// A SQLite failure during `operation`: the name of the public method whose statement
    /// failed.
    fn sqlite(operation: &'static str, source: rusqlite::Error) -> Self {
        Self::Sqlite { operation, source }
    }
}

impl fmt::Display for RepoError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Sqlite { operation, source } => write!(f, "{operation}: {source}"),
            Self::Status(text) => write!(
                f,
                "a session row holds the status \"{text}\", which is not one of: {}",
                Status::ALL.map(Status::as_str).join(", ")
            ),
        }
    }
}

impl std::error::Error for RepoError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Sqlite { source, .. } => Some(source),
            Self::Status(_) => None,
        }
    }
}
