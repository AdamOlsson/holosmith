//! The `sessions` row: what a session is stored as, and the types the repository stores it with
//!
//!
//! The six statuses live in an enum here rather than in a `CHECK` constraint, so a corrupt row is
//! an error at read time naming the text that was found, and the transition rules arrive without
//! a migration that has to rewrite a constraint (ADR-0011).

pub(crate) mod activity;
pub mod repository;
pub mod state;

use std::fmt;
use std::str::FromStr;

use serde::Serialize;

/// One of the six session statuses, spelled exactly as the spec spells them (item 8).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Status {
    Starting,
    Idle,
    Running,
    Stopped,
    Error,
    Deleting,
}

impl Status {
    /// Every status, in the spec's order: one list for the state filter, the error message and
    /// the tests.
    pub const ALL: [Status; 6] = [
        Status::Starting,
        Status::Idle,
        Status::Running,
        Status::Stopped,
        Status::Error,
        Status::Deleting,
    ];

    /// The text the `status` column holds.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Starting => "starting",
            Self::Idle => "idle",
            Self::Running => "running",
            Self::Stopped => "stopped",
            Self::Error => "error",
            Self::Deleting => "deleting",
        }
    }
}

impl FromStr for Status {
    type Err = RepoError;

    /// Anything that is not one of the six is refused with the text that was found, so a corrupt
    /// row says which value it holds instead of a bare "invalid status".
    fn from_str(text: &str) -> Result<Self, Self::Err> {
        Self::ALL
            .into_iter()
            .find(|status| status.as_str() == text)
            .ok_or_else(|| RepoError::Status(text.to_string()))
    }
}

impl fmt::Display for Status {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// The wire word is `as_str`, the same function the `status` column is written with, so the two
/// cannot diverge. A derive would be a second spelling of the six words.
impl Serialize for Status {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(self.as_str())
    }
}

/// Whether `id` has the shape a session id has: sixteen lowercase hexadecimal characters (ADR-0011).
///
/// One home, because more than one place asks the same question about a string that came from somewhere else —
/// the preview listener's path, `container snapshot`'s `HS_SESSION_ID`, and anything that must decide
/// "could this be a row" before it reads one. A second copy would be a second answer to "what is an id".
pub fn is_id(id: &str) -> bool {
    id.len() == 16
        && id
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase())
}

/// One `sessions` row. `PartialEq` is what makes "reads back identically" an assertion rather
/// than a field-by-field ceremony.
///
/// The field set is the table's, in column order, and the wire shape is the row: `Option` fields
/// serialise as explicit `null`. The one extra key a create's response carries (`events`) belongs
/// to the HTTP wrapper in `http::sessions`, not here.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Session {
    /// 16 lowercase hexadecimal characters, generated by SQLite (ADR-0011).
    pub id: String,
    pub project: String,
    pub model: String,
    pub thinking: String,
    /// `''` until the provisioner runs.
    pub worktree: String,
    /// `None` until a worktree exists.
    pub base_commit: Option<String>,
    pub status: Status,
    pub status_reason: Option<String>,
    /// The idempotency key the create carried; `None` is not a key.
    pub client_key: Option<String>,
    /// The spec's `network INTEGER` column, as the checkbox a client sends.
    pub network: bool,
    pub created_at: i64,
    /// What the cap's LRU eviction orders by (spec item 7).
    pub last_active_at: i64,
    /// `Some` exactly while the status is `stopped`: set when it becomes stopped, cleared when
    /// the session resumes (spec item 15).
    pub stopped_at: Option<i64>,
    pub usage_in: u64,
    pub usage_out: u64,
}

/// What a caller supplies to create a session; everything else is the repository's or `now`.
#[derive(Debug, Clone)]
pub struct NewSession {
    pub project: String,
    pub model: String,
    pub thinking: String,
    pub network: bool,
    pub client_key: Option<String>,
    pub base_commit: Option<String>,
}

/// Why a repository call failed.
#[derive(Debug)]
pub enum RepoError {
    /// SQLite refused a statement of the named call, so an operator reading
    /// `create: database is locked` knows which one — the same convention `DbError::Sqlite`
    /// follows by naming the file it is about.
    Sqlite {
        operation: &'static str,
        source: rusqlite::Error,
    },
    /// A row's `status` is not one of the six; it carries the text that was found.
    Status(String),
    /// A create carried an idempotency key another session already holds.
    DuplicateClientKey,
}

impl RepoError {
    /// A SQLite failure during `operation`: the name of the public method whose statement
    /// failed.
    ///
    /// `pub(crate)`: `push::repository` reuses this error as its own, the way
    /// `events::repository` does, so the crate keeps one repository error rather than two shapes of
    /// "a statement failed".
    pub(crate) fn sqlite(operation: &'static str, source: rusqlite::Error) -> Self {
        Self::Sqlite { operation, source }
    }
}

impl fmt::Display for RepoError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Sqlite { operation, source } => write!(f, "{operation}: {source}"),
            Self::Status(text) => write!(
                f,
                "a session row holds the status \"{text}\", which is not one of: {}",
                Status::ALL.map(Status::as_str).join(", ")
            ),
            Self::DuplicateClientKey => {
                f.write_str("create: a session already holds this client key")
            }
        }
    }
}

impl std::error::Error for RepoError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Sqlite { source, .. } => Some(source),
            Self::Status(_) | Self::DuplicateClientKey => None,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_status_serialises_as_the_word_its_column_holds() {
        for status in Status::ALL {
            assert_eq!(
                serde_json::to_string(&status).expect("a status is one JSON string"),
                format!("\"{}\"", status.as_str()),
                "{status} did not serialise through as_str"
            );
        }
    }

    #[test]
    fn a_session_serialises_to_the_fifteen_column_names_in_column_order() {
        // Key order is declaration order, which is column order, so one exact string pins both
        // the field set and the order. `Option` fields are explicit `null`: one stable shape.
        let session = Session {
            id: "0123456789abcdef".to_string(),
            project: "holosmith".to_string(),
            model: "claude-sonnet-4.5".to_string(),
            thinking: "high".to_string(),
            worktree: String::new(),
            base_commit: None,
            status: Status::Starting,
            status_reason: None,
            client_key: Some("the-key".to_string()),
            network: true,
            created_at: 1_760_000_000,
            last_active_at: 1_760_000_000,
            stopped_at: None,
            usage_in: 0,
            usage_out: 0,
        };
        assert_eq!(
            serde_json::to_string(&session).expect("fifteen fields always serialise"),
            concat!(
                r#"{"id":"0123456789abcdef","project":"holosmith","#,
                r#""model":"claude-sonnet-4.5","thinking":"high","worktree":"","#,
                r#""base_commit":null,"status":"starting","status_reason":null,"#,
                r#""client_key":"the-key","network":true,"created_at":1760000000,"#,
                r#""last_active_at":1760000000,"stopped_at":null,"usage_in":0,"usage_out":0}"#
            )
        );
    }
}
